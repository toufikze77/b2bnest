// HMRC P2: what the browser collects for HMRC's fraud prevention headers (connection method WEB_APP_VIA_SERVER,
// specification v3.3, read on the HMRC Developer Hub on 4 Nov 2026). Only the browser-side items on HMRC's list:
//   Gov-Client-Device-ID           → deviceId      (a random UUID kept in this browser; not tied to the person)
//   Gov-Client-Browser-JS-User-Agent → jsUserAgent (navigator.userAgent, as the browser reports it)
//   Gov-Client-Screens             → screens       (width, height, scaling factor, colour depth)
//   Gov-Client-Window-Size         → windowSize    (window width and height in pixels)
//   Gov-Client-Timezone            → timezone      (UTC±hh:mm)
//   Gov-Vendor-Version (web part)  → webVersion
// The server adds the rest (IP, timestamp, user id, multi-factor, vendor details) and does the encoding.
// Nothing is guessed: a value the browser can't give is left out, and the server then omits that header.

export const HMRC_DEVICE_ID_KEY = 'b2bnest.hmrc.deviceId';
/** The version of the B2BNEST web app sent in Gov-Vendor-Version (our own label; package.json has no release number). */
export const WEB_APP_VERSION = '1.0.0';

export interface BrowserFraudData {
  deviceId?: string;
  jsUserAgent?: string;
  screens?: { width: number; height: number; scalingFactor: number; colourDepth: number }[];
  windowSize?: { width: number; height: number };
  timezone?: string;
  webVersion: string;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
let memoryDeviceId: string | null = null;

function newUuid(): string {
  const c = globalThis.crypto;
  if (c && typeof c.randomUUID === 'function') return c.randomUUID();
  const b = new Uint8Array(16);
  c.getRandomValues(b);
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

/**
 * HMRC: "generated by an application and persistently stored on the device… should not expire… If your end user
 * deletes the device ID, you need to generate a new one". Kept in localStorage; when storage is blocked, one id is
 * kept in memory for this page instead.
 */
export function hmrcDeviceId(): string {
  try {
    const kept = localStorage.getItem(HMRC_DEVICE_ID_KEY);
    if (kept && UUID.test(kept)) return kept.toLowerCase();
    const id = newUuid();
    localStorage.setItem(HMRC_DEVICE_ID_KEY, id);
    return id;
  } catch {
    memoryDeviceId ??= newUuid();
    return memoryDeviceId;
  }
}

const posInt = (n: unknown): n is number => typeof n === 'number' && Number.isInteger(n) && n > 0;

/** UTC±hh:mm from the browser's current offset (getTimezoneOffset is minutes behind UTC). */
export function utcOffset(offsetMinutesBehindUtc: number): string | undefined {
  if (!Number.isFinite(offsetMinutesBehindUtc)) return undefined;
  const ahead = -Math.round(offsetMinutesBehindUtc);
  const abs = Math.abs(ahead);
  if (abs > 14 * 60) return undefined;
  const hh = String(Math.floor(abs / 60)).padStart(2, '0');
  const mm = String(abs % 60).padStart(2, '0');
  return `UTC${ahead < 0 ? '-' : '+'}${hh}:${mm}`;
}

/** The browser-side data for HMRC's fraud prevention headers. Never throws. */
export function collectHmrcFraudData(): BrowserFraudData {
  const out: BrowserFraudData = { webVersion: WEB_APP_VERSION };
  out.deviceId = hmrcDeviceId();
  try {
    const ua = typeof navigator !== 'undefined' ? navigator.userAgent : '';
    if (ua && ua.trim()) out.jsUserAgent = ua;
  } catch { /* left out */ }
  try {
    const s = typeof screen !== 'undefined' ? screen : null;
    const scaling = typeof window !== 'undefined' ? window.devicePixelRatio : undefined;
    if (s && posInt(s.width) && posInt(s.height) && posInt(s.colorDepth) && typeof scaling === 'number' && scaling > 0) {
      out.screens = [{ width: s.width, height: s.height, scalingFactor: scaling, colourDepth: s.colorDepth }];
    }
  } catch { /* left out */ }
  try {
    if (typeof window !== 'undefined' && posInt(window.innerWidth) && posInt(window.innerHeight)) {
      out.windowSize = { width: window.innerWidth, height: window.innerHeight };
    }
  } catch { /* left out */ }
  try {
    const tz = utcOffset(new Date().getTimezoneOffset());
    if (tz) out.timezone = tz;
  } catch { /* left out */ }
  return out;
}
